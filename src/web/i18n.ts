const dicts: Record<Lang, Record<Key, string>> = { zh, en };

export type T = (key: Key, vars?: Record<string, string | number>) => string;

export function makeT(lang: Lang): T {
  return (key, vars) => {
    let s = dicts[lang][key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}

export function errorText(t: T, code: string) {
  const key = `err.${code}` as Key;
  return key in zh ? t(key) : t("err.internal");
}

export function relativeTime(ms: number, lang: Lang, t: T) {
  const diff = Date.now() - ms;
  if (diff < 60_000) return t("time.now");
  const rtf = new Intl.RelativeTimeFormat(lang === "zh" ? "zh-CN" : "en", { numeric: "auto", style: "short" });
  const min = Math.round(diff / 60_000);
  if (min < 60) return rtf.format(-min, "minute");
  const h = Math.round(min / 60);
  if (h < 24) return rtf.format(-h, "hour");
  const d = Math.round(h / 24);
  if (d < 7) return rtf.format(-d, "day");
  const date = new Date(ms);
  const sameYear = date.getFullYear() === new Date().getFullYear();
  return date.toLocaleDateString(lang === "zh" ? "zh-CN" : "en", {
    month: "short",
    day: "numeric",
    ...(sameYear ? {} : { year: "numeric" }),
  });
}

export function shortDate(ms: number, lang: Lang, timeZone?: string) {
  return new Date(ms).toLocaleDateString(lang === "zh" ? "zh-CN" : "en", { month: "short", day: "numeric", timeZone });
}
